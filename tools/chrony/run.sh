#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# tools/chrony/run.sh: co-simulation of the server-only design with a real
# chronyd (task CHRONY). Run tools/chrony/build.sh first.
#
#   tools/chrony/run.sh [SCENARIO...]     (default: all scenarios below)
#
# Scenarios (results in out/chrony/results/<scenario>/):
#   fixed       FixedSync stratum 2, default limiter (8/s), minpoll 0 maxpoll 2
#               iburst, 300 virtual s: acceptance, selection, offset, ntpdata
#   standalone  stratum 16 / LI 3 (unsynchronised), 60 virtual s
#   ratelimit   --rate-limit 1, minpoll -2 (4 polls/s) iburst, 60 virtual s:
#               what chrony does when most replies are withheld
#   rl-iburst   --rate-limit 1, minpoll 0 maxpoll 2 iburst, 30 virtual s
#   burst       default limiter (8/s) against minpoll -4 (16 polls/s), 30 s
#   offset      as fixed but noselect, minpoll 0 maxpoll 0, 64 virtual s: raw
#               offsets (chronyd does not discipline its clock to a noselect
#               source), compared with the bench's ground truth
#   xleave      chrony's interleaved mode against our basic-mode server
#   extfield    chrony's experimental extension field F323 (76-byte requests)
#   version3    NTPv3 requests
#   version2    NTPv2 requests (the server answers VN 3 and 4 only)
#   noff        no fast-forward: every one of the 3e7 cycles of 0.3 virtual s
#               simulated (minpoll -7 = 7.8 ms, noselect; chronyd's first
#               request leaves at 0.2 s): validates the skipping of idle
#               cycles used by every other scenario (about 4 minutes)
#
# Each scenario: the bridge (rtl/src/bin/chrony_bridge.rs) listens on
# 127.0.0.1:$PORT and publishes the simulation's virtual time in a shared
# page; chronyd runs under the time shim (LD_PRELOAD vtime_shim.so) with -x
# (never touches the host clock), -d (foreground, log on stderr), a private
# configuration, a private UNIX command socket and no UDP command port.
# When the bridge reaches the virtual duration it stops and time freezes;
# then chronyc (`sources -v`, `sourcestats -v`, `ntpdata`, `tracking`) is
# run against chronyd's socket and chronyd is stopped. analyse.py checks.
#
# Files per scenario: bridge.log (status lines, hex dump of every payload),
# exchanges.csv (one line per answered request, ground truth of the bench),
# chronyd.log, measurements.log / statistics.log / tracking.log (chrony's
# logs), chronyc-*.txt, chrony.conf.
#
# Wall time: a few seconds to a minute per scenario (the idle time between
# polls is skipped, see the bridge header).
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT="$ROOT/out/chrony"
BRIDGE="$ROOT/target/release/chrony_bridge"
CHRONYD="$OUT/inst/sbin/chronyd"
CHRONYC="$OUT/inst/bin/chronyc"
SHIM="$OUT/vtime_shim.so"
PORT=${PORT:-12300}

for f in "$BRIDGE" "$CHRONYD" "$CHRONYC" "$SHIM"; do
    [ -e "$f" ] || { echo "missing $f: run tools/chrony/build.sh" >&2; exit 1; }
done

# scenario -> "bridge options|server options|virtual duration (s)"
spec() {
    case "$1" in
    fixed) echo "--sync fixed --rate-limit 8|minpoll 0 maxpoll 2 iburst|${DURATION:-300}" ;;
    offset) echo "--sync fixed --rate-limit 8|minpoll 0 maxpoll 0 noselect|64" ;;
    standalone) echo "--sync standalone --rate-limit 8|minpoll 0 maxpoll 2 iburst|60" ;;
    ratelimit) echo "--sync fixed --rate-limit 1|minpoll -2 maxpoll -2 iburst|60" ;;
    rl-iburst) echo "--sync fixed --rate-limit 1|minpoll 0 maxpoll 2 iburst|30" ;;
    burst) echo "--sync fixed --rate-limit 8|minpoll -4 maxpoll -4|30" ;;
    xleave) echo "--sync fixed --rate-limit 8|minpoll 0 maxpoll 0 xleave|30" ;;
    extfield) echo "--sync fixed --rate-limit 8|minpoll 0 maxpoll 0 extfield F323|30" ;;
    version3) echo "--sync fixed --rate-limit 8|minpoll 0 maxpoll 0 version 3|30" ;;
    noff) echo "--sync fixed --rate-limit 8 --no-ff|minpoll -7 maxpoll -7 noselect|0.3" ;;
    version2) echo "--sync fixed --rate-limit 8|minpoll 0 maxpoll 0 version 2|20" ;;
    *) echo "unknown scenario $1" >&2; exit 2 ;;
    esac
}

run_one() {
    local name=$1
    local s bopts sopts dur
    s=$(spec "$name")
    bopts=${s%%|*}
    s=${s#*|}
    sopts=${s%%|*}
    dur=${s#*|}
    local R="$OUT/results/$name"
    rm -rf "$R"
    mkdir -p "$R"
    chmod 700 "$R"
    # UNIX socket paths are limited to 107 bytes: a short private directory.
    local S
    S=$(mktemp -d "${TMPDIR:-/tmp}/chrony-cosim.XXXXXX")
    chmod 700 "$S"
    cat >"$R/chrony.conf" <<EOF
# Generated by tools/chrony/run.sh (scenario $name)
server 127.0.0.1 port $PORT $sopts
# The virtual clock has a 1 ns resolution; do not let chronyd measure it
# (it would spin on a clock that stands still while it computes).
clockprecision 0.000000001
cmdport 0
bindcmdaddress $S/chronyd.sock
pidfile $S/chronyd.pid
logdir $R
log measurements statistics tracking rawmeasurements
EOF
    echo "== $name: bridge $bopts, server $sopts, $dur virtual s"
    local t0=$SECONDS
    # shellcheck disable=SC2086
    "$BRIDGE" --shm "$R/vtime.shm" --port "$PORT" $bopts --duration "$dur" \
        --log "$R/exchanges.csv" --hexdump --status 5 --max-wall 1800 2>"$R/bridge.log" &
    local bpid=$!
    for _ in $(seq 100); do
        [ -s "$R/vtime.shm" ] && break
        sleep 0.05
    done
    CHRONY_VTIME_SHM="$R/vtime.shm" LD_PRELOAD="$SHIM" \
        "$CHRONYD" -x -d -f "$R/chrony.conf" 2>"$R/chronyd.log" &
    local cpid=$!
    wait "$bpid" || echo "bridge exited with $?" >&2
    for c in "sources -v" "sourcestats -v" "ntpdata" "tracking"; do
        "$CHRONYC" -h "$S/chronyd.sock" $c >"$R/chronyc-${c%% *}.txt" 2>&1 || true
    done
    kill "$cpid" 2>/dev/null || true
    wait "$cpid" 2>/dev/null || true
    rm -rf "$S"
    tail -n 1 "$R/bridge.log"
    echo "   wall time $((SECONDS - t0)) s"
}

if [ $# -eq 0 ]; then
    set -- fixed offset standalone ratelimit rl-iburst burst xleave extfield version3 version2 noff
fi
for n in "$@"; do
    run_one "$n"
done
python3 -I "$ROOT/tools/chrony/analyse.py" "$OUT/results" "$@"
