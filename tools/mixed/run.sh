#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# tools/mixed/run.sh: combined scenario, in ONE simulation (same server
# instance, same MII wire, same virtual time): ntpperf generates load while a
# chronyd polls the server as one more client (docs/ntpperf-results.md,
# section "Scénario combiné", and docs/chrony-interop.md, section 8).
# Run tools/chrony/build.sh and tools/ntpperf/build.sh first.
#
#   tools/mixed/run.sh [--long] [--base] [--jobs N] [JOB...]     (default: the jobs below, 3 at a time)
#
# --base also runs, for each job, its twin without chronyd (results/<job>-base/): analyse.py then
# checks that ntpperf's own per-request log is unchanged by chronyd's presence.
#
# The bridge is tools/ntpperf/ntpperf_bridge with --chrony-port: it owns the
# virtual time of both clients (ntpperf under pcap_shim/vtime.c, chronyd under
# tools/chrony/vtime_shim.c, two shared pages with the same time), lets it
# advance only when ntpperf's processes AND chronyd are all waiting, turns
# chronyd's UDP requests into frames (192.168.123.2, 02:00:00:00:00:03) that
# enter the same sender-queue model as ntpperf's, and gives chronyd the replies
# addressed to it at the virtual instant their last nibble leaves the MII pins.
#
# Jobs (name: ntpperf options | chronyd `server` options), bridge --rate-limit 0:
#   select    -B -t 12 -r 2000      | minpoll 0 maxpoll 0 iburst    chrony selects the server under load
#   offset    -B -t 12 -r 2000      | minpoll 0 maxpoll 0 noselect  raw offsets vs. the bench's ground truth
#   mid       -B -t 1  -r 20000     | minpoll -4 maxpoll -4 noselect  18 % of the line rate, 16 polls/s: some requests wait
# --long adds (a one-second point of ntpperf near the line rate costs 4e7 cycles per half second):
#   heavy     -B -t 1  -r 105000    | minpoll -3 maxpoll -3 noselect  just under the line rate (96 %)
#   sel-heavy -B -t 1  -r 105000    | minpoll -3 maxpoll -3 iburst
# RATE / TSEC override ntpperf's -r / -t of select and offset.
#
# Results in out/mixed/results/<job>/: ntpperf.txt, bridge.log, requests.csv,
# cmd.txt (as the ntpperf jobs: checked by tools/ntpperf/analyse.py), chrony.csv
# (one line per chronyd exchange: the bench's ground truth), chronyd.log,
# measurements.log, chronyc-*.txt, chrony.conf; then tools/mixed/analyse.py.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT="$ROOT/out/mixed"
RES="$OUT/results"
BRIDGE="$ROOT/target/release/ntpperf_bridge"
NTPPERF="$ROOT/out/ntpperf/src/ntpperf"
NSHIM="$ROOT/out/ntpperf/ntpperf_vtime.so"
CHRONYD="$ROOT/out/chrony/inst/sbin/chronyd"
CHRONYC="$ROOT/out/chrony/inst/bin/chronyc"
CSHIM="$ROOT/out/chrony/vtime_shim.so"
PORT=${PORT:-12301}
RATE=${RATE:-2000}
TSEC=${TSEC:-12}
NJOBS=3
BASE=0
LONG=0
SEL=()
while [ $# -gt 0 ]; do
    a=$1
    case "$a" in
    --long) LONG=1 ;;
    --jobs) NJOBS=$2; shift ;;
    --base) BASE=1 ;;
    -h|--help) sed -n '3,30p' "$0"; exit 0 ;;
    *) SEL+=("$a") ;;
    esac
    shift
done
for f in "$BRIDGE" "$NTPPERF" "$NSHIM" "$CHRONYD" "$CHRONYC" "$CSHIM"; do
    [ -e "$f" ] || { echo "missing $f: run tools/chrony/build.sh and tools/ntpperf/build.sh" >&2; exit 1; }
done

NET="-i sim0 -m 02:00:00:00:00:01 -d 192.168.123.1 -s 172.18.0.0/16"
# name|ntpperf options|chronyd server options
specs() {
    cat <<EOF
select|-B -t $TSEC -r $RATE|minpoll 0 maxpoll 0 iburst
offset|-B -t $TSEC -r $RATE|minpoll 0 maxpoll 0 noselect
mid|-B -t 1 -r 20000|minpoll -4 maxpoll -4 noselect
EOF
    if [ "$LONG" = 1 ]; then
        echo "heavy|-B -t 1 -r 105000|minpoll -3 maxpoll -3 noselect"
        echo "sel-heavy|-B -t 1 -r 105000|minpoll -3 maxpoll -3 iburst"
    fi
}

selected() {
    [ ${#SEL[@]} -eq 0 ] && return 0
    local s
    for s in "${SEL[@]}"; do [ "$s" = "$1" ] && return 0; done
    return 1
}

run_one() {
    local name=$1 nopts=$2 sopts=$3 PORT=$4
    local R="$RES/$name"
    rm -rf "$R"
    mkdir -p "$R"
    chmod 700 "$R"
    # UNIX socket paths are limited to 107 bytes: a short private directory.
    local S
    S=$(mktemp -d "${TMPDIR:-/tmp}/mixed-cosim.XXXXXX")
    chmod 700 "$S"
    cat >"$R/chrony.conf" <<EOF
# Generated by tools/mixed/run.sh (job $name)
server 127.0.0.1 port $PORT $sopts
clockprecision 0.000000001
cmdport 0
bindcmdaddress $S/chronyd.sock
pidfile $S/chronyd.pid
logdir $R
log measurements statistics tracking rawmeasurements
EOF
    echo "== $name: ntpperf $nopts, chronyd $sopts (UDP port $PORT)"
    local t0=$SECONDS
    # shellcheck disable=SC2086
    echo "$BRIDGE --shim $NSHIM --shm $R/vtime.shm --rate-limit 0 --chrony-port $PORT --chrony-shm $R/chrony.shm --chrony-log $R/chrony.csv --log $R/requests.csv -- $NTPPERF $NET $nopts" >"$R/cmd.txt"
    # shellcheck disable=SC2086
    "$BRIDGE" --shim "$NSHIM" --shm "$R/vtime.shm" --rate-limit 0 --chrony-port "$PORT" \
        --chrony-shm "$R/chrony.shm" --chrony-log "$R/chrony.csv" --log "$R/requests.csv" \
        --status 30 --max-wall 7200 -- "$NTPPERF" $NET $nopts >"$R/ntpperf.txt" 2>"$R/bridge.log" &
    local bpid=$!
    for _ in $(seq 100); do
        [ -s "$R/chrony.shm" ] && break
        sleep 0.05
    done
    CHRONY_VTIME_SHM="$R/chrony.shm" LD_PRELOAD="$CSHIM" \
        "$CHRONYD" -x -d -f "$R/chrony.conf" 2>"$R/chronyd.log" &
    local cpid=$!
    wait "$bpid" || echo "bridge exited with $?" >>"$R/bridge.log"
    for c in "sources -v" "sourcestats -v" "ntpdata" "tracking"; do
        "$CHRONYC" -h "$S/chronyd.sock" $c >"$R/chronyc-${c%% *}.txt" 2>&1 || true
    done
    kill "$cpid" 2>/dev/null || true
    wait "$cpid" 2>/dev/null || true
    rm -rf "$S"
    rm -f "$R/vtime.shm" "$R/chrony.shm"
    echo "$((SECONDS - t0))" >"$R/wall_s.txt"
    tail -n 6 "$R/bridge.log" | cut -c1-300
    echo "   wall time $((SECONDS - t0)) s"
}

# The same ntpperf load without chronyd (same bridge, no --chrony-*).
run_base() {
    local name=$1 nopts=$2
    local R="$RES/$name-base"
    rm -rf "$R"
    mkdir -p "$R"
    echo "== $name-base: ntpperf $nopts, no chronyd"
    local t0=$SECONDS
    # shellcheck disable=SC2086
    echo "$BRIDGE --shim $NSHIM --shm $R/vtime.shm --rate-limit 0 --log $R/requests.csv -- $NTPPERF $NET $nopts" >"$R/cmd.txt"
    # shellcheck disable=SC2086
    "$BRIDGE" --shim "$NSHIM" --shm "$R/vtime.shm" --rate-limit 0 --log "$R/requests.csv" \
        --status 30 --max-wall 7200 -- "$NTPPERF" $NET $nopts >"$R/ntpperf.txt" 2>"$R/bridge.log" ||
        echo "bridge exited with $?" >>"$R/bridge.log"
    rm -f "$R/vtime.shm"
    echo "$((SECONDS - t0))" >"$R/wall_s.txt"
    echo "   wall time $((SECONDS - t0)) s"
}

mkdir -p "$RES"
i=0
while IFS='|' read -r name n s; do
    selected "$name" || continue
    # One port per job: the jobs run side by side.
    ( run_one "$name" "$n" "$s" $((PORT + i)) >"$RES/$name.out" 2>&1; cat "$RES/$name.out" ) &
    i=$((i + 1))
    if [ "$BASE" = 1 ]; then
        ( run_base "$name" "$n" >"$RES/$name-base.out" 2>&1; cat "$RES/$name-base.out" ) &
        while [ "$(jobs -rp | wc -l)" -ge "$NJOBS" ]; do wait -n || true; done
    fi
    while [ "$(jobs -rp | wc -l)" -ge "$NJOBS" ]; do wait -n || true; done
done < <(specs)
wait
# ntpperf's own numbers (loss, response time, TX offset): the checks of tools/ntpperf/analyse.py
# on the same directories; then the chronyd side and the comparison between the two.
rc=0
python3 -I "$ROOT/tools/ntpperf/analyse.py" "$RES" "${SEL[@]}" >"$RES/ntpperf-summary.txt" || rc=1
tail -n 3 "$RES/ntpperf-summary.txt"
python3 -I "$ROOT/tools/mixed/analyse.py" "$RES" "${SEL[@]}" || rc=1
exit $rc
